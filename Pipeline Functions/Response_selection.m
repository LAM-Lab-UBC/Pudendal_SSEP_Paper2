function [Response_elect] = Response_selection(peak)
    % List of options
    ResponseOpt = {'Yes','No'};
    
    % Build the prompt string
    peak = string(peak);
    if peak == "Overall"
        msgResponse = 'Is there an identifiable response?';
    else
        msgResponse = sprintf('Is there an identifiable %s location?', peak);
    end

    % % Create a modal dialog at [x y w h] (in pixels)
    % dlgW = 350; dlgH = 140;
    % % e.g. x=500, y=500 — you can change these to wherever you like
    % x = 1500; y = 450;  
    % d = dialog( ...
    %     'Name',             'Response Selection', ...
    %     'Position',         [x y dlgW dlgH], ...
    %     'WindowStyle',      'modal'            ...  % blocks MATLAB until closed
    % );

    dlgW = 350; dlgH = 140;
    % e.g. x=500, y=500 — you can change these to wherever you like
    x = 1500; y = 450;  
    d = dialog( ...
        'Name',             'Response Selection', ...
        'WindowStyle',      'modal',            ... 
        'Units',       'normalized', ...
        'Position',    [0.7 0.42  0.19 0.18] ...  % [left bottom width height]
    );

    % Message text
    uicontrol( ...
        'Parent',   d, ...
        'Style',    'text', ...
        'Position', [20 70 dlgW-40 50], ...
        'String',   msgResponse, ...
        'FontSize', 11, ...
        'HorizontalAlignment','left' ...
    );

    % % “Yes” button
    % uicontrol( ...
    %     'Parent',   d, ...
    %     'Style',    'pushbutton', ...
    %     'String',   ResponseOpt{1}, ...
    %     'Position', [ 60 20 100 30], ...
    %     'Callback', @(src,~) onChoice(src, d) ...
    % );
    % 
    % % “No” button
    % uicontrol( ...
    %     'Parent',   d, ...
    %     'Style',    'pushbutton', ...
    %     'String',   ResponseOpt{2}, ...
    %     'Position', [190 20 100 30], ...
    %     'Callback', @(src,~) onChoice(src, d) ...
    % );

 % Yes button
    uicontrol(d,'Style','pushbutton', ...
                 'Units','normalized', ...
                 'String','Yes', ...
                 'Position',[0.10 0.15 0.35 0.20], ...
                 'Callback',@(src,~)onChoice(src,d));

    % No button
    uicontrol(d,'Style','pushbutton', ...
                 'Units','normalized', ...
                 'String','No', ...
                 'Position',[0.55 0.15 0.35 0.20], ...
                 'Callback',@(src,~)onChoice(src,d));

    % Wait for the user to click
    uiwait(d);

    % Retrieve and return their choice
    Response_elect = getappdata(d, 'UserChoice');
    delete(d);
end

function onChoice(src, dlg)
    % Store the button text, then resume execution
    setappdata(dlg, 'UserChoice', src.String);
    uiresume(dlg);
end
